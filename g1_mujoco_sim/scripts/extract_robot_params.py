#!/usr/bin/env python3
"""Regenerate the ``robot:`` section of the locomotion config from the URDF.

Every rigid-body number the controllers need (mass, centroidal inertia, nominal
CoM height, foot contact-point offsets, stance width, the base height that puts
the soles exactly on the ground) is a consequence of the URDF and the nominal
joint configuration.  Hard-coding them is how they drift apart from the model,
so they are computed here with xbot2_interface and written back into the YAML.

Usage:
    rosrun g1_mujoco_sim extract_robot_params.py            # rewrite the config
    rosrun g1_mujoco_sim extract_robot_params.py --check    # verify, non-zero exit on drift
"""

import argparse
import os
import sys

import numpy as np

from xbot2_interface import pyxbot2_interface as xbi

# Contact points are ordered L-heel, L-toe, R-heel, R-toe everywhere in this
# stack.  Any table indexed by contact point uses this order.
CONTACT_FRAMES = [
    "left_foot_line_contact_lower",
    "left_foot_line_contact_upper",
    "right_foot_line_contact_lower",
    "right_foot_line_contact_upper",
]
FOOT_FRAMES = ["left_foot_point_contact", "right_foot_point_contact"]

PKG_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_URDF = os.path.join(PKG_DIR, os.pardir, "g1_description", "g1_23dof.urdf")
DEFAULT_YAML = os.path.join(PKG_DIR, "config", "g1_locomotion.yaml")


def skew(v):
    return np.array([[0.0, -v[2], v[1]], [v[2], 0.0, -v[0]], [-v[1], v[0], 0.0]])


def compute(urdf_path, q_nominal):
    """Return the robot-derived parameters as a plain dict."""
    with open(urdf_path, "r") as f:
        model = xbi.ModelInterface2(f.read())

    q = np.asarray(q_nominal, dtype=float)
    if q.size != model.nq:
        raise ValueError("nominal configuration has %d entries, model wants %d"
                         % (q.size, model.nq))

    model.setJointPosition(q)
    model.setJointVelocity(np.zeros(model.nv))
    model.update()

    mass = model.getMass()
    com = model.getCOM()
    base = model.getPose("pelvis").translation

    # Composite (locked) rigid-body inertia about the CoM.  The top-left 6x6
    # block of the joint-space inertia matrix is the locked inertia at the base
    # frame origin; shifting it to the CoM with the parallel-axis term gives the
    # centroidal inertia the single-rigid-body model actually needs.  Using the
    # inertia about the pelvis instead makes the MPC think the robot is much
    # harder to rotate than it is.
    lever = com - base
    S = skew(lever)
    inertia = model.computeInertiaMatrix()[3:6, 3:6] + mass * (S @ S)
    inertia = 0.5 * (inertia + inertia.T)  # kill asymmetry from round-off

    # Cross-check against the centroidal momentum matrix, which is the same
    # quantity by a different route.
    ag = model.computeCentroidalMomentumMatrix()[3:6, 3:6]
    if not np.allclose(inertia, 0.5 * (ag + ag.T), atol=1e-6):
        raise RuntimeError("centroidal inertia cross-check failed")

    # Foot geometry, expressed in the foot (point-contact) frame so it stays
    # valid when the robot turns.
    foot_pts = {name: model.getPose(name).translation for name in CONTACT_FRAMES}
    feet = {name: model.getPose(name).translation for name in FOOT_FRAMES}

    heel_x = float(foot_pts[CONTACT_FRAMES[0]][0] - feet[FOOT_FRAMES[0]][0])
    toe_x = float(foot_pts[CONTACT_FRAMES[1]][0] - feet[FOOT_FRAMES[0]][0])

    sole_z = float(np.mean([p[2] for p in foot_pts.values()]))
    stance_width = float(feet[FOOT_FRAMES[0]][1] - feet[FOOT_FRAMES[1]][1])
    # Where the foot sits relative to the CoM in the nominal stance. The
    # footstep planner aims here rather than directly under the CoM, so a
    # standing command reproduces the nominal posture instead of dragging the
    # feet forwards under the body.
    foot_offset_x = float(feet[FOOT_FRAMES[0]][0] - com[0])

    return {
        "mass": float(mass),
        "inertia": [[float(v) for v in row] for row in inertia],
        # CoM height measured from the soles, not from the world origin, so it
        # stays correct whatever base height the model is spawned at.
        "com_height": float(com[2] - sole_z),
        "base_height": float(base[2] - sole_z),
        "foot_heel_x": heel_x,
        "foot_toe_x": toe_x,
        "stance_width": stance_width,
        "foot_offset_x": foot_offset_x,
        "contact_frames": list(CONTACT_FRAMES),
        "foot_frames": list(FOOT_FRAMES),
    }


def render(params):
    """Render the robot section as YAML text (no pyyaml dependency needed)."""
    inertia = params["inertia"]
    lines = [
        "  # ---- generated by scripts/extract_robot_params.py, do not hand-edit ----",
        "  mass: %.6f" % params["mass"],
        "  # Centroidal composite inertia at the nominal configuration [kg m^2].",
        "  inertia:",
    ]
    for row in inertia:
        lines.append("    - [%14.8e, %14.8e, %14.8e]" % tuple(row))
    lines += [
        "  # CoM height above the soles at the nominal configuration [m].",
        "  com_height: %.6f" % params["com_height"],
        "  # Pelvis height that puts the soles exactly on the ground [m].",
        "  base_height: %.6f" % params["base_height"],
        "  # Heel/toe offsets along x in the foot frame [m].",
        "  foot_heel_x: %.6f" % params["foot_heel_x"],
        "  foot_toe_x: %.6f" % params["foot_toe_x"],
        "  # Nominal lateral distance between the two feet [m].",
        "  stance_width: %.6f" % params["stance_width"],
        "  # Nominal foot position relative to the CoM, along x [m].",
        "  foot_offset_x: %.6f" % params["foot_offset_x"],
        "  contact_frames:",
    ]
    for name in params["contact_frames"]:
        lines.append("    - %s" % name)
    lines.append("  foot_frames:")
    for name in params["foot_frames"]:
        lines.append("    - %s" % name)
    return "\n".join(lines)


def splice(yaml_text, rendered):
    """Replace the body of the top-level ``robot:`` block."""
    begin = "robot:\n"
    start = yaml_text.index(begin) + len(begin)
    end = start
    for line in yaml_text[start:].splitlines(keepends=True):
        if line.strip() and not line.startswith((" ", "\t")):
            break
        end += len(line)
    return yaml_text[:start] + rendered + "\n\n" + yaml_text[end:].lstrip("\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--urdf", default=DEFAULT_URDF)
    ap.add_argument("--yaml", default=DEFAULT_YAML)
    ap.add_argument("--check", action="store_true",
                    help="only report whether the YAML matches the URDF")
    args = ap.parse_args()

    sys.path.insert(0, os.path.join(PKG_DIR, "src"))
    from g1_mujoco_sim.nominal_configuration import Q_NOMINAL

    params = compute(args.urdf, Q_NOMINAL)
    rendered = render(params)

    with open(args.yaml, "r") as f:
        text = f.read()

    updated = splice(text, rendered)
    if args.check:
        if updated != text:
            print("config is stale with respect to %s" % args.urdf)
            return 1
        print("config matches the URDF")
        return 0

    with open(args.yaml, "w") as f:
        f.write(updated)
    print("wrote robot parameters to %s" % args.yaml)
    print(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main())
